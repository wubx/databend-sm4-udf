#!/usr/bin/env python3
"""Generate deployment SQL offline; no connections and no database changes."""
import argparse
from pathlib import Path
import re
from urllib.parse import urlparse

ROOT=Path(__file__).resolve().parents[1]


def generate(python_address='http://127.0.0.1:8815',wasm_path='@sm4_udf/databend_sm4_udf.wasm',compat=False):
    url=urlparse(python_address)
    if url.scheme not in ('http','https') or not url.hostname or url.username or url.password:
        raise ValueError('Python address must be http(s)://host:port, without credentials')
    if url.path not in ('','/') or url.query or url.fragment or any(c in python_address for c in "'\n\r"):
        raise ValueError('Invalid Python server address')
    if not re.fullmatch(r'@[A-Za-z_][A-Za-z0-9_]*/[A-Za-z0-9_./-]+\.wasm',wasm_path):
        raise ValueError('WASM path must be @stage/path.wasm')
    source=(ROOT/'javascript/sm4.mjs').read_text()
    outputs={}
    for impl in ('js','wasm','python'):
        statements=['-- Generated by scripts/generate_sql.py. Re-running replaces ONLY the named functions.\n']
        profiles=('default_iv','explicit_iv') if compat else ('',)
        for profile,op in ((profile,op) for profile in profiles for op in ('encrypt','decrypt')):
            name=f'sm4_{op}_{profile+"_" if profile else ""}{impl}'
            signature='BINARY NULL, STRING NULL, STRING NULL, STRING NULL' if compat else 'BINARY NULL, BINARY NULL, BINARY NULL, STRING NULL'
            prefix=f'''CREATE OR REPLACE FUNCTION {name}
({signature})
RETURNS BINARY NULL\n'''
            if impl=='python':body=f"LANGUAGE python HANDLER = '{name}' ADDRESS = '{python_address}';"
            else:
                language='javascript' if impl=='js' else 'wasm'
                module='\n'+source if impl=='js' else wasm_path
                body=f"LANGUAGE {language} HANDLER = '{name}' AS $${module}$$;"
            statements.append(prefix+body+'\n')
        outputs[f'{"compat_" if compat else ""}{impl}.sql']='\n'.join(statements)
    return outputs


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--python-address',default='http://127.0.0.1:8815')
    p.add_argument('--wasm-path',default='@sm4_udf/databend_sm4_udf.wasm')
    p.add_argument('--check',action='store_true',help='Fail if generated files differ, without writing')
    args=p.parse_args()
    outputs=generate(args.python_address,args.wasm_path)
    outputs.update(generate(args.python_address,args.wasm_path,compat=True))
    for name,sql in outputs.items():
        path=ROOT/'sql'/name
        if args.check:
            if not path.exists() or path.read_text()!=sql:raise SystemExit(f'Stale generated SQL: {path}')
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(sql)
        print(path)


if __name__=='__main__':main()
